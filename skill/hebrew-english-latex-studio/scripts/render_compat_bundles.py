#!/usr/bin/env python3
"""Render/check generated compatibility bundles from pure architecture layers."""
from __future__ import annotations

from pathlib import Path
import argparse
import sys

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
sys.path.insert(0, str(ROOT / "scripts"))
from architecture_contract import ASSET_SPECS  # noqa: E402
from render_architecture_guards import render_guard  # noqa: E402

HEADER = r'''% ============================================================================
% clean_variant.tex — GENERATED backward-compatible bundle.
% DO NOT EDIT THIS FILE DIRECTLY.
% Sources of truth:
%   clean_theme.tex      — presentation / presentation-policy
%   exam_components.tex  — semantic exam helpers
% Existing documents may keep \input{clean_variant.tex}; new compositions should
% load the pure layers explicitly when they need only one responsibility.
% ============================================================================
'''


def runtime_guard() -> str:
    """Render the carrier guard from the canonical architecture schema."""
    spec = next(spec for spec in ASSET_SPECS if spec.path == "assets/clean_variant.tex")
    return render_guard(spec) + "\n\n"


def marked_body(path: Path, name: str) -> str:
    text = path.read_text(encoding="utf-8")
    start = f"% <hllpdf:{name}>\n"
    end = f"% </hllpdf:{name}>"
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError(f"{path.name}: expected exactly one marker pair for {name}")
    return text.split(start, 1)[1].split(end, 1)[0]


def render() -> str:
    theme = marked_body(ASSETS / "clean_theme.tex", "clean-theme-body")
    components = marked_body(ASSETS / "exam_components.tex", "exam-components-body")
    # Preserve the historical executable order: graphicx first, then clean
    # presentation, then exam helper definitions. Comments/header are free to
    # change; TeX semantics stay source-compatible.
    return HEADER + runtime_guard() + "\\usepackage{graphicx}\n\n" + theme + "\n" + components


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true", help="fail if clean_variant.tex is stale")
    p.add_argument("--write", action="store_true", help="rewrite clean_variant.tex from pure layers")
    args = p.parse_args()
    if args.check == args.write:
        p.error("choose exactly one of --check or --write")
    dest = ASSETS / "clean_variant.tex"
    expected = render()
    if args.check:
        if not dest.exists() or dest.read_text(encoding="utf-8") != expected:
            print("✗ clean_variant.tex drifted from clean_theme.tex + exam_components.tex")
            return 1
        print("✓ generated compatibility bundle matches pure architecture layers")
        return 0
    dest.write_text(expected, encoding="utf-8")
    print(f"✓ wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
