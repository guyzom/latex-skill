#!/usr/bin/env python3
"""Generate/check Studio catalog and glossary from their canonical records.

No TeX engine, font installer or renderer is invoked. Check mode never writes.
"""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path, PurePosixPath
import sys
import tempfile
from typing import Any

sys.dont_write_bytecode = True

from architecture_contract import ARCHITECTURE_SCHEMA_VERSION, ASSET_SPECS, HOOK_SPECS
from studio_glossary import MARKDOWN_PATH, ROOT, load_records, render_markdown, source_reference
from template_registry import load_catalog

CATALOG_MARKDOWN = "references/template-catalog.md"


def cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", "<br>")


def code(value: Any) -> str:
    return "`" + cell(value) + "`"


def source_link(path: str) -> str:
    return f"[{PurePosixPath(path).name}](../{path})"


def glossary_links(ids: list[str]) -> str:
    return ", ".join(f"[{key}](glossary-he-en.md#term-{key})" for key in ids)


def title(record: dict[str, Any]) -> str:
    return cell(record["title"]["he"]) + " — " + cell(record["title"]["en"])


def starter_table(starters: list[dict[str, Any]]) -> list[str]:
    out = ["| Native source language | Starter | Authored declarations |", "|---|---|---|"]
    for starter in starters:
        hooks = "; ".join(f"{code(key)} = {code(value)}" for key, value in starter["declared_hooks"].items())
        out.append(f"| {code(starter['language'])} | {source_link(starter['asset_path'])} | {hooks or 'None'} |")
    return out


def build_defaults_table(defaults: list[list[str]]) -> list[str]:
    return [f"{code(key)}={code(value)}" for key, value in defaults]


def record_notes(record: dict[str, Any]) -> list[str]:
    links = ", ".join(source_link(path) for path in record["docs"])
    return [
        "", f"Guides: {links}.",
        f"Vocabulary: {glossary_links(record['glossary_refs'])}.",
        "Acceptance case identifiers: " + ", ".join(code(case) for case in record["acceptance"]) + ".", "",
    ]


def render_catalog(catalog: Any, skill_version: str) -> str:
    """Render canonical typed records; no alternative recipe tables are maintained."""
    data = catalog.as_dict()
    chunks = [
        "<!-- Generated by scripts/generate_studio_docs.py; edit registry/studio-catalog.json and the owning contracts. -->",
        "# Template catalog — קטלוג התבניות", "",
        f"Hebrew–English LaTeX Studio **v{skill_version}**; catalog schema **{data['schema_version']}**; "
        f"architecture schema **{ARCHITECTURE_SCHEMA_VERSION}**.", "",
        "This catalog is generated from [the canonical registry](../registry/studio-catalog.json). "
        "It lists available recipes and declared acceptance cases; it does not claim that an engine, "
        "renderer or visual reviewer has run for the current release. Execution evidence is retained separately.", "",
        "זהו קטלוג אחד לעברית, לאנגלית ולמסמכים משולבים. בחירת שפה, ייעוד, פריסה ועיצוב נשארת עצמאית, "
        "במסגרת המגבלות המוצהרות. קובצי הדוגמה הם נקודת התחלה לעריכה; החלף תוכן ומטא־נתונים לפני מסירה.", "",
        "Use [the workflow](everyday-workflow.md) to create a project, [the glossary](glossary-he-en.md) "
        "to understand terms, and [the developer guide](catalog-development.md) to extend the skill.", "",
        "## Inspect before creating", "",
        "Run these read-only commands from the actual skill root:", "", "```bash",
        "python3 scripts/template_registry.py list",
        "python3 scripts/template_registry.py validate --json",
        "python3 scripts/template_registry.py resolve --kind paper --language english --json",
        "python3 scripts/template_registry.py resolve --kind formula-sheet --language hebrew \\",
        "  --layout reference-readable --json", "```", "",
        "An explicit theme has precedence over a layout default, a template default, then the catalog default. "
        "Every choice remains subject to the layout, language and component constraints. "
        "`bilingual` requires `--main-language hebrew` or `english`; both languages are available in every profile.", "",
        "## Document templates", "",
        "| `--kind` | Purpose — ייעוד | Default layout | Default theme | Advisory content profile |",
        "|---|---|---|---|---|",
    ]
    for record in data["templates"]:
        default_theme = code(record["default_theme"]) if record["default_theme"] is not None else "Catalog default"
        chunks.append(f"| {code(record['id'])} | {title(record)} | {code(record['default_layout'])} | {default_theme} | {code(record['content_profile'])} |")
    chunks.extend(["", "A kind names a purpose, not a LaTeX class. Native authored declarations below are preserved as written. "
                   "A layout may replace the selected starter or override a declaration. All five profiles are supported; "
                   "the two explicit bilingual bases make six language configurations for acceptance coverage.", ""])
    for record in data["templates"]:
        chunks.extend([f"### Template {record['id']}", "", f"**{title(record)}**. Recipe revision: {record['recipe_revision']}.", ""])
        chunks.extend(starter_table(record["starters"]))
        chunks.extend(["", "Bilingual composer: " + code(record["bilingual_composer_id"]) +
                       "; minority-language composer: " + code(record["minority_composer_id"]) + "."])
        chunks.append("Additional copied components: " + (", ".join(source_link(path) for path in record["copy_extra"]) or "None") + ".")
        if record["build_defaults"]:
            chunks.append("Build verification defaults: " + ", ".join(build_defaults_table(record["build_defaults"])) + ".")
        if record["source_handlers"]:
            chunks.append("Closed source handlers: " + ", ".join(code(value) for value in record["source_handlers"]) + ".")
        chunks.extend(record_notes(record))
    chunks.extend(["## Layout presets", "", "| `--layout` | Description | Allowed kinds | Default theme when omitted |", "|---|---|---|---|"])
    for record in data["layouts"]:
        kinds = ", ".join(code(value) for value in record["allowed_kinds"])
        default = code(record["default_theme"]) if record["default_theme"] is not None else "Template/catalog default"
        chunks.append(f"| {code(record['id'])} | {title(record)} | {kinds} | {default} |")
    chunks.extend(["", "Preset values are authored settings, never an automatic fit-to-page operation. "
                   "Reference numerical font sizes use TeX points, not PDF big points. "
                   "Layout ownership remains in the core hooks and the selected layout extension.", ""])
    for record in data["layouts"]:
        chunks.extend([f"### Layout {record['id']}", "", f"**{title(record)}**. Recipe revision: {record['recipe_revision']}.", ""])
        if record["starter_overrides"]:
            chunks.append("This preset selects the following native starters before applying overrides:")
            chunks.append("")
            chunks.extend(starter_table(record["starter_overrides"]))
            chunks.append("")
        if record["hook_overrides"]:
            chunks.extend(["| Hook | Literal value | Owner | Unit | Declaration phase |", "|---|---|---|---|---|"])
            for hook in record["hook_overrides"]:
                chunks.append(f"| {code(hook['name'])} | {code(hook['value'])} | {source_link(hook['owner'])} | {code(hook['unit'])} | {code(hook['phase'])} |")
            chunks.append("")
        chunks.append("Layout components: " + (", ".join(source_link(path) for path in record["components"]) or "None") + ".")
        if record["build_defaults"]:
            chunks.append("Build verification defaults: " + ", ".join(build_defaults_table(record["build_defaults"])) + ".")
        chunks.extend(record_notes(record))
    chunks.extend(["## Presentation choices", "", "| ID | Description | Availability | Source/mode | Caption labels |", "|---|---|---|---|---|"])
    for record in data["themes"]:
        source = source_link(record["asset_path"]) if record["asset_path"] is not None else code(record["mode"])
        caption = record["caption_contract"]
        chunks.append(f"| {code(record['id'])} | {title(record)} | {code(record['exposure'])} | {source} | {code(caption['label_color'])}; {code(caption['label_weight'])} |")
    chunks.extend(["", "Only `generator-supported` choices are accepted by `new_document.py --theme`. "
                   "`clean` is a direct-input theme and `legacy-clean` inventories a compatibility bundle. "
                   "They do not add new generator CLI choices. `core` keeps core presentation; "
                   "`custom` creates an editable local theme skeleton. Choose one presentation policy.", ""])
    for record in data["themes"]:
        chunks.extend([f"### Theme {record['id']}", "", f"**{title(record)}**."])
        if record["build_defaults"]:
            chunks.append("Build verification defaults: " + ", ".join(build_defaults_table(record["build_defaults"])) + ".")
        chunks.extend(record_notes(record))
    chunks.extend(["## Maintained examples", "", "Examples demonstrate components and compatibility paths; they are not additional document kinds.", "",
                   "| Example ID | Source | Declared profile | Architecture components |", "|---|---|---|---|"])
    for record in data["examples"]:
        assets = ", ".join(source_link(path) for path in record["architecture_assets"])
        chunks.append(f"| {code(record['id'])} | {source_link(record['asset_path'])} | {code(record['language_profile'])} | {assets} |")
    for record in data["examples"]:
        chunks.extend(["", f"### Example {record['id']}"])
        chunks.extend(record_notes(record))
    chunks.extend(["## Component ownership", "", "The following inventory is derived from `architecture_contract.ASSET_SPECS`. "
                   "The template catalog references these owners instead of declaring another component system.", "",
                   "| Source | Role | Provided capabilities |", "|---|---|---|"])
    for asset in ASSET_SPECS:
        capabilities = ", ".join(code(value) for value in asset.provides)
        chunks.append(f"| {source_link(asset.path)} | {code(asset.role)} | {capabilities or 'None'} |")
    chunks.extend(["", "Dependencies, conflicts, public symbols and hook timing are documented in "
                   "[the architecture contract](architecture.md) and validated against their owning code. "
                   "Copy order and TeX load order are separate plans.", "",
                   "## Public hook inventory", "",
                   "This table is generated from `architecture_contract.HOOK_SPECS`. "
                   "Symbolic defaults describe the owner's rule and are not measured numeric values. "
                   "Only hooks marked as preset-configurable can appear as catalog hook overrides; "
                   "language and presentation remain in their respective contracts.", "",
                   "| Hook | Owner | Define before | Scope | Value type / unit | Default / kind | Allowed values / minimum | Preset configurable |",
                   "|---|---|---|---|---|---|---|---|"])
    for hook in HOOK_SPECS:
        before = source_link(hook.define_before) if hook.define_before else "Owning style API"
        unit = code(hook.unit) if hook.unit else "No physical unit"
        constraints = ", ".join(code(value) for value in hook.allowed_values)
        if hook.minimum is not None:
            constraints += ("; " if constraints else "") + (">= " if hook.minimum_inclusive else "> ") + code(hook.minimum)
        chunks.append(f"| {code(hook.name)} | {source_link(hook.owner)} | {before} | {code(hook.scope)} | "
                      f"{code(hook.value_type)} / {unit} | {code(hook.default)} / {code(hook.default_kind)} | {constraints or 'Owner contract'} | {'Yes' if hook.preset_allowed else 'No'} |")
    chunks.extend(["",
                   "## Documentation maintenance", "", "Required catalog vocabulary: " + glossary_links(data["required_glossary_terms"]) + ".", "",
                   "To regenerate both this catalog and the maintained glossary, run `python3 scripts/generate_studio_docs.py`. "
                   "`--check` validates source records, references, glossary coverage, the current release version and exact generated bytes without writing. "
                   "It is a documentation check, not a build or visual approval."])
    return "\n".join(chunks).rstrip() + "\n"


def generated_documents(root: Path) -> dict[str, bytes]:
    root = Path(root)
    catalog = load_catalog(root, allow_missing_generated_docs=True)
    for collection in ("templates", "layouts", "themes", "examples"):
        for record in catalog.as_dict()[collection]:
            for path in record["docs"]:
                source_reference(root, path, f"catalog {record['id']}", allow_missing_generated=True)
    records = load_records(root, catalog=catalog, allow_missing_generated=True)
    version = (root / "VERSION").read_text(encoding="utf-8").strip()
    return {
        CATALOG_MARKDOWN: render_catalog(catalog, version).encode("utf-8"),
        MARKDOWN_PATH: render_markdown(records).encode("utf-8"),
    }


def write_document(path: Path, content: bytes) -> None:
    """Replace one generated document atomically; the two-file set is not a transaction."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary: str | None = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".studio-doc-", delete=False) as stream:
            temporary = stream.name
            stream.write(content)
        mode = path.stat().st_mode & 0o777 if path.exists() else 0o644
        os.chmod(temporary, mode)
        os.replace(temporary, path)
        temporary = None
    finally:
        if temporary is not None:
            Path(temporary).unlink(missing_ok=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help="Actual extracted skill root")
    parser.add_argument("--check", action="store_true", help="Verify exact generated bytes without writing")
    args = parser.parse_args(argv)
    try:
        documents = generated_documents(args.root)
        if args.check:
            stale = [path for path, content in documents.items() if not (args.root / path).is_file() or (args.root / path).read_bytes() != content]
            if stale:
                raise ValueError("generated documentation differs: " + ", ".join(stale))
        else:
            for path, content in documents.items():
                write_document(args.root / path, content)
        for path, content in documents.items():
            print(f"{'PASS' if args.check else 'Generated'}: {path}; SHA-256 {hashlib.sha256(content).hexdigest()}")
        if args.check:
            print("No files written; no engine, render or release validation claimed.")
    except (ValueError, OSError, TypeError, KeyError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
